/* ------------------------------------------------------------ utilities */
export function productById(id) {
  return PRODUCTS.find((product) => product.id === id);
}

export function productsByCategory(categoryId) {
  if (categoryId === 'all') return PRODUCTS;
  return PRODUCTS.filter((product) => product.category === categoryId);
}

export function bestSellers(limit = 8) {
  return [...PRODUCTS].sort((a, b) => b.reviews - a.reviews).slice(0, limit);
}

export function discounts(limit = 8) {
  return PRODUCTS.filter((product) => product.oldPrice).slice(0, limit);
}

export function searchProducts(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PRODUCTS.filter((product) => {
    const haystack = [
      product.name.bn,
      product.name.en,
      product.category,
      product.origin?.bn,
      product.origin?.en,
    ]
      .filter(Boolean)
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
}
